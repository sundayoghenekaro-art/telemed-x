-- Synthetic dataset for capacity tests T1 (baseline clinical read) and T3
-- (peak device-write) from SCALABILITY_AUDIT.md.
--
-- THIS IS NOT A MIGRATION. It is a manual script for a throwaway staging
-- database. It refuses to run unless the operator opts in inside the same
-- session first:
--
--   set app.staging_seed = 'yes';
--   set app.seed_patients = '10000';
--   set app.seed_vitals_per_patient = '50';
--   \i scripts/staging-seed.sql
--
-- Identifiers are random UUIDs, not auth.users rows: patient_vitals has no
-- foreign key to auth, so no login is created and nothing is email-verifiable.

set statement_timeout = 0;

do $$
begin
  if coalesce(current_setting('app.staging_seed', true), '') <> 'yes' then
    raise exception
      'Refusing to seed: run "set app.staging_seed = ''yes'';" first, on staging only.';
  end if;
end
$$;

select set_config('app.seed_patients', coalesce(current_setting('app.seed_patients', true), '10000'), false) as seed_patients;
select set_config('app.seed_vitals_per_patient', coalesce(current_setting('app.seed_vitals_per_patient', true), '50'), false) as vitals_per_patient;

create temp table seed_patients on commit drop as
select gen_random_uuid() as patient_user_id
from generate_series(1, current_setting('app.seed_patients')::int);

-- Vitals: newest reading per patient is what the monitoring console reads.
insert into public.patient_vitals (
  patient_user_id, heart_rate, blood_pressure_systolic, blood_pressure_diastolic,
  temperature, spo2, respiratory_rate, weight, blood_glucose, source, recorded_at
)
select
  p.patient_user_id,
  60 + (random() * 40)::int,
  100 + (random() * 40)::int,
  60 + (random() * 30)::int,
  round((36.2 + random() * 1.4)::numeric, 2),
  94 + (random() * 6)::int,
  12 + (random() * 8)::int,
  round((55 + random() * 60)::numeric, 2),
  70 + (random() * 90)::int,
  'device',
  now() - (g * interval '5 minutes')
from seed_patients p
cross join generate_series(1, current_setting('app.seed_vitals_per_patient')::int) as g;

-- Medical records: the paginated list covers the (patient_user_id, created_at)
-- index introduced in 20261101160000.
insert into public.patient_medical_records (
  patient_user_id, title, record_type, provider_name, record_date, notes, created_at
)
select
  p.patient_user_id,
  'Synthetic record ' || g,
  (array['lab_test', 'lab_report', 'radiology_report', 'prescription'])[1 + (g % 4)],
  'Synthetic facility ' || (1 + (g % 12)),
  (now() - (g * interval '9 days'))::date,
  'Synthetic row generated by scripts/staging-seed.sql',
  now() - (g * interval '3 days')
from seed_patients p
cross join generate_series(1, 20) as g;

-- Notifications: exercises the notification list keyset pagination.
insert into public.patient_notifications (patient_user_id, title, message, type, read, created_at)
select
  p.patient_user_id,
  'Synthetic notification ' || g,
  'Generated for capacity testing',
  'info',
  g % 2 = 0,
  now() - (g * interval '6 hours')
from seed_patients p
cross join generate_series(1, 10) as g;

analyze public.patient_vitals;
analyze public.patient_medical_records;
analyze public.patient_notifications;

select
  (select count(*) from public.patient_vitals) as vitals_rows,
  (select count(*) from public.patient_medical_records) as medical_record_rows,
  (select count(*) from public.patient_notifications) as notification_rows;
