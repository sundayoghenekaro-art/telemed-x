const DAY = 86_400_000;

function iso(daysFromNow: number, hour = 9, minute = 0): string {
  const date = new Date(Date.now() + daysFromNow * DAY);
  date.setHours(hour, minute, 0, 0);
  return date.toISOString();
}

function buildCaptions(transcript: TranscriptSection[], durationSec: number): CaptionCue[] {
  const cues: CaptionCue[] = [];
  transcript.forEach((section, index) => {
    const nextStart = transcript[index + 1]?.startSec ?? durationSec;
    const span = Math.max(8, nextStart - section.startSec);
    const sentences = section.text.split(/(?<=[.!?])\s+/).filter(Boolean);
    const slice = span / Math.max(1, sentences.length);
    sentences.forEach((sentence, sentenceIndex) => {
      cues.push({
        id: `${section.id}-c${sentenceIndex + 1}`,
        startSec: Math.round(section.startSec + slice * sentenceIndex),
        endSec: Math.round(section.startSec + slice * (sentenceIndex + 1)),
        text: sentence,
      });
    });
  });
  return cues;
}

type ContentSeed = Omit<ContentItem, 'synthetic' | 'chapters' | 'captions'>;

function makeContent(seed: ContentSeed): ContentItem {
  return {
    ...seed,
    synthetic: true,
    chapters: seed.transcript.map((section) => ({
      id: `${section.id}-chapter`,
      label: section.title,
      startSec: section.startSec,
    })),
    captions: buildCaptions(seed.transcript, seed.durationSec),
  };
}

